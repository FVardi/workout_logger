"""The Postgres adapter (training.pg).

The schema translation is tested offline. The round-trip tests need a real
Postgres and run only when TEST_DATABASE_URL points at one, e.g.

    TEST_DATABASE_URL=postgresql://postgres@127.0.0.1:5432/postgres python -m pytest tests/test_pg.py

Each run works in a fresh schema, so it never touches existing tables.
"""

import os
import uuid

import pytest

from training import db, pg


def test_schema_translation_makes_ids_identities_and_reals_doubles():
    out = pg.schema_for_postgres(db.SCHEMA_PATH.read_text())
    assert "id            INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in out
    assert "INTEGER PRIMARY KEY REFERENCES users(id)" in out   # user_settings.user_id stays a plain key
    assert "REAL" not in out.replace("DOUBLE PRECISION", "")


def test_inserts_into_tables_with_an_id_get_returning():
    assert pg._INSERT_WITH_ID.match("INSERT INTO sets (block_id) VALUES (?)")
    assert not pg._INSERT_WITH_ID.match("INSERT INTO user_settings (user_id) VALUES (?)")


URL = os.environ.get("TEST_DATABASE_URL")
needs_pg = pytest.mark.skipif(not URL, reason="TEST_DATABASE_URL not set")


@pytest.fixture
def conn():
    psycopg = pytest.importorskip("psycopg")
    schema = f"test_{uuid.uuid4().hex[:10]}"
    with psycopg.connect(URL, autocommit=True) as admin:
        admin.execute(f"CREATE SCHEMA {schema}")
    sep = "&" if "?" in URL else "?"
    c = db.connect(f"{URL}{sep}options=-csearch_path%3D{schema}")
    try:
        yield c
    finally:
        c.close()
        for pool in list(pg._pools.values()):
            pool.close()
        pg._pools.clear()
        with psycopg.connect(URL, autocommit=True) as admin:
            admin.execute(f"DROP SCHEMA {schema} CASCADE")


@needs_pg
def test_round_trip_users_sessions_blocks_sets(conn):
    uid = db.create_user(conn, "a@example.com", "hash")
    assert db.get_user_by_email(conn, "a@example.com")["id"] == uid
    assert db.get_user_settings(conn, uid).volume_multiplier == 1.0
    sid = db.get_or_create_session(conn, uid, "2026-10-29")
    assert db.get_or_create_session(conn, uid, "2026-10-29") == sid
    group = db.next_piece_group(conn, sid)
    bid = db.log_block(conn, sid, "heavy", structure="5x5", summary="Back squat 5x5", piece_group=group)
    for _ in range(5):
        db.log_set(conn, bid, "back_squat", 10, reps=5, load=102.5)
    conn.commit()
    (piece,) = db.fetch_pieces(conn, uid)
    assert piece["styles"] == ["heavy"] and len(piece["sets"]) == 5
    assert piece["sets"][0]["load"] == 102.5            # double precision, not float4
    assert db.heaviest_load_for_exercise(conn, uid, "back_squat") == 102.5
    assert [s.exercise_id for s in db.fetch_sets(conn, uid)] == ["back_squat"] * 5
    assert db.delete_piece(conn, uid, sid, group)
    assert db.fetch_pieces(conn, uid) == []
