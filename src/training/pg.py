"""Postgres behind the sqlite3 interface db.py already uses.

db.py is written against sqlite3 (`?` placeholders, `cursor.lastrowid`,
rows readable both as tuples and by column name). Rather than rewrite every
query for a second database, this module wraps a psycopg connection so the
same calls work unchanged:

- `?` placeholders become `%s`.
- `INSERT INTO` a table with an `id` column gets `RETURNING id`, which fills
  `lastrowid`. (`user_settings` has no `id` column and doesn't need one.)
- Rows behave like `sqlite3.Row`: tuple-unpackable, indexable by name,
  `dict(row)` works.

Only the subset of the sqlite3 API that db.py calls is implemented. SQLite
stays the default for local use and tests; Postgres is for the hosted
version, where the host's disk isn't persistent (see docs/STATUS.md).

Requires the `postgres` extra: `pip install -e .[postgres]`.
"""

from __future__ import annotations

import re
import threading

_INSERT_WITH_ID = re.compile(
    r"^\s*INSERT\s+INTO\s+(users|sessions|blocks|sets|parse_runs|parse_outcomes)\b", re.IGNORECASE)

_pools: dict[str, object] = {}
_pools_lock = threading.Lock()


def is_postgres_url(path: str) -> bool:
    return path.startswith(("postgres://", "postgresql://"))


class Row(tuple):
    """A result row usable like sqlite3.Row."""

    def __new__(cls, values, names, index):
        row = super().__new__(cls, values)
        row._names = names
        row._index = index
        return row

    def __getitem__(self, key):
        if isinstance(key, str):
            return tuple.__getitem__(self, self._index[key])
        return tuple.__getitem__(self, key)

    def keys(self):
        return list(self._names)


def _row_factory(cursor):
    names = [c.name for c in cursor.description] if cursor.description else []
    index = {n: i for i, n in enumerate(names)}
    return lambda values: Row(values, names, index)


class Cursor:
    def __init__(self, cur, lastrowid=None):
        self._cur = cur
        self.lastrowid = lastrowid

    def fetchone(self):
        return self._cur.fetchone()

    def fetchall(self):
        return self._cur.fetchall()

    def __iter__(self):
        return iter(self._cur.fetchall())


class Connection:
    """The sqlite3.Connection subset db.py uses, over a pooled psycopg connection."""

    dialect = "postgres"

    def __init__(self, raw, pool):
        self._raw = raw
        self._pool = pool
        self.row_factory = None  # accepted and ignored; rows are always Row

    @staticmethod
    def _translate(sql: str) -> str:
        return sql.replace("?", "%s")

    def execute(self, sql: str, params=()):
        sql = self._translate(sql)
        cur = self._raw.cursor(row_factory=_row_factory)
        if _INSERT_WITH_ID.match(sql) and "RETURNING" not in sql.upper():
            cur.execute(sql + " RETURNING id", tuple(params))
            return Cursor(cur, lastrowid=cur.fetchone()[0])
        cur.execute(sql, tuple(params))
        return Cursor(cur)

    def executemany(self, sql: str, seq):
        cur = self._raw.cursor()
        cur.executemany(self._translate(sql), [tuple(p) for p in seq])
        return Cursor(cur)

    def executescript(self, script: str):
        self._raw.execute(script)

    def commit(self):
        self._raw.commit()

    def rollback(self):
        self._raw.rollback()

    def close(self):
        if self._raw is None:
            return
        try:
            self._raw.rollback()  # never hand an open transaction back to the pool
        finally:
            self._pool.putconn(self._raw)
            self._raw = None


def connect(url: str) -> Connection:
    """A pooled connection. One pool per URL per process: opening a fresh TLS
    connection to a hosted database on every request is the slow part."""
    from psycopg_pool import ConnectionPool

    with _pools_lock:
        pool = _pools.get(url)
        if pool is None:
            pool = ConnectionPool(url, min_size=1, max_size=5, open=True,
                                  kwargs={"autocommit": False})
            _pools[url] = pool
    return Connection(pool.getconn(), pool)


def schema_for_postgres(sqlite_schema: str) -> str:
    """schema.sql is written for SQLite. Two differences matter:
    `id INTEGER PRIMARY KEY` auto-increments in SQLite but needs an identity
    column in Postgres, and SQLite's REAL is a double while Postgres's REAL is
    single precision, and BLOB is BYTEA."""
    out = re.sub(r"(?m)^(\s*id\s+)INTEGER PRIMARY KEY",
                 r"\1INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY", sqlite_schema)
    out = re.sub(r"\bREAL\b", "DOUBLE PRECISION", out)
    return re.sub(r"\bBLOB\b", "BYTEA", out)


def table_columns(conn: Connection, table: str) -> set[str]:
    rows = conn.execute(
        "SELECT column_name AS name FROM information_schema.columns "
        "WHERE table_schema = current_schema() AND table_name = ?",
        (table,),
    ).fetchall()
    return {r["name"] for r in rows}
